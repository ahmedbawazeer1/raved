/**
 * npm run placement:seed -- <path-slug>
 * Validates content/<path>/placement.json and writes a migration that imports it.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { bankProblems, placementBankSchema } from "../src/lib/placement/bank";

const slug = process.argv[2] ?? "english";
const file = path.join(__dirname, "..", "content", slug, "placement.json");
const parsed = placementBankSchema.safeParse(JSON.parse(readFileSync(file, "utf8")));
if (!parsed.success) {
  console.log(`✗ ${file}\n${parsed.error.issues.map((i) => `   ${i.path.join(".")}: ${i.message}`).join("\n")}`);
  process.exit(1);
}
const problems = bankProblems(parsed.data);
if (problems.length) {
  console.log(`✗ ${file}\n${problems.map((p) => `   ${p}`).join("\n")}`);
  process.exit(1);
}

const stamp = new Date().toISOString().replace(/\D/g, "").slice(0, 14);
const out = path.join(__dirname, "..", "supabase", "migrations", `${stamp}_placement_${slug}_v${parsed.data.version}.sql`);
const json = JSON.stringify(parsed.data);
if (json.includes("$bank$")) throw new Error("unexpected delimiter in content");
writeFileSync(
  out,
  `-- Generated by scripts/placement-seed.ts from content/${slug}/placement.json (do not edit by hand).\n` +
    `select public.import_placement_bank('${slug}', $bank$${json}$bank$::jsonb);\n`,
);
console.log(`✓ ${parsed.data.questions.length} أسئلة ← ${path.relative(process.cwd(), out)}`);
